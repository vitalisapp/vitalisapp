const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '');

// One flat entry per plan spelling, shaped like exerciseGuide() output so the
// frontend can merge both lists.
function planExerciseGuides() {
  return PLAN_GUIDES.flatMap(({ names, muscle, steps, cues, mistakes }) =>
    names.map((name) => ({ name, muscle, steps, cues, mistakes, level: 1, impact: 'low' })));
}

module.exports = { PLAN_GUIDES, planExerciseGuides, norm };
