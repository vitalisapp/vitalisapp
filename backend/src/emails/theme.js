// Deployed frontend that serves frontend/public/email/ in production.
const PRODUCTION_ASSET_BASE_URL = "https://vitalisapp-eta.vercel.app/email";

/**
 * Base URL for email assets, picked by NODE_ENV:
 *   production  → EMAIL_ASSET_BASE_URL, else the Vercel deploy
 *   development → FRONTEND_URL/email (localhost; Gmail can't load these)
 * @returns {string}
 */
function assetBaseUrl() {
  const base =
    process.env.NODE_ENV === "production"
      ? process.env.EMAIL_ASSET_BASE_URL || PRODUCTION_ASSET_BASE_URL
      : `${frontendUrl()}/email`;
  return base.replace(/\/$/, "");
}

/**
 * Absolute URL for an email asset.
 * @param {keyof typeof ICONS | string} name
 * @returns {string}
 */
function assetUrl(name) {
  const file = ICONS[name] || name;
  return `${assetBaseUrl()}/${file}`;
}

/**
 * Absolute link into the web app.
 * @param {string} [path]
 * @returns {string}
 */
function appUrl(path = "") {
  return `${frontendUrl()}${path.startsWith("/") || !path ? path : `/${path}`}`;
}

module.exports = { BRAND, ICONS, assetUrl, appUrl };
